export const catName = (id: string): string =>
  CATS.find((c) => c.id === id)?.name ?? String(id ?? '');

// 本文のかたまりを、検索用の「ただの文字」に変えます。
export const blockText = (b: Block): string => {
  if (typeof b === 'string') return b;
  if ('h' in b) return b.h;
  if ('ul' in b) return b.ul.join(' ');
  if ('ol' in b) return b.ol.map((s) => `${s.t} ${s.d ?? ''}`).join(' ');
  if ('kv' in b) return b.kv.map((x) => `${x.k} ${x.v}`).join(' ');
  if ('table' in b) return `${b.table.head.join(' ')} ${b.table.rows.map((r) => r.join(' ')).join(' ')}`;
  if ('tip' in b) return b.tip;
  if ('warn' in b) return b.warn;
  if ('code' in b) return b.code;
  if ('link' in b) return b.link.label;
  return '';
};

