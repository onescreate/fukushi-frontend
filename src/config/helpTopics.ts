// 福祉システムの説明書の中身（データ）。
//
// ★ここに置いた理由
//   説明書の画面（pages/HelpPage.tsx）だけでなく、「質問はこちら」（AIチャット）からも
//   同じ本文を読ませるためです。画面のファイルに文章で書いたままだと取り出せません。
//
// 【書き方】1件＝1つの説明。TOPICS に足すだけで、説明書の検索にもAIの回答にも入ります。
//   id    … 変えてはいけない合言葉。記録や「よくある質問」の集計がこれで紐づきます。
//   cat   … 分類（下の CATS の id）
//   aud   … 読者（beginner はじめて / ops 毎日の担当 / admin 管理者）
//   title … 見出し
//   kw    … 検索用の言葉（本文に無い言い回しを補う）
//   body  … 本文。下の Block のどれか。

export type Block =
  | string
  | { h: string }
  | { ul: string[] }
  | { ol: { t: string; d?: string }[] }
  | { kv: { k: string; v: string }[] }
  | { table: { head: string[]; rows: string[][] } }
  | { tip: string }
  | { warn: string }
  | { code: string }
  | { link: { to: string; label: string } };

export type Audience = 'beginner' | 'ops' | 'admin';

export interface Topic {
  id: string;
  cat: string;
  aud: Audience[];
  title: string;
  kw: string;
  body: Block[];
}

